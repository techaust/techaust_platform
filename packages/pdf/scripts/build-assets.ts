// Build-time assets of the PDF engine (M4.4): the fonts as data URIs, the print CSS, the brand logos and the symbol, written to
// src/generated/assets.ts (committed; a drift test regenerates it and compares). Node only.
// Run: pnpm --filter @techaust/pdf build:assets
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BRAND_LOGOS } from "@techaust/core/settings";
import { PDF_FALLBACK_FONTS, pdfFallbackFileName, unicodeRange } from "../../ui/src/fonts/config.ts";

const UI = fileURLToPath(new URL("../../ui/", import.meta.url));
const OUT = fileURLToPath(new URL("../src/generated/assets.ts", import.meta.url));

/** The UI font files used in documents (IBM Plex Mono only when the designer asks). */
export const FONT_FILES = ["archivo-latin.woff2", "archivo-rupee.woff2"] as const;

const read = (rel: string) => readFileSync(`${UI}${rel}`);
const text = (rel: string) => readFileSync(`${UI}${rel}`, "utf8").replace(/\r\n/g, "\n");

/** The SVG as an inline element: XML prolog stripped, and refused if it could run script or load anything. */
export function cleanSvg(name: string, raw: string): string {
  const svg = raw.replace(/^\s*<\?xml[^>]*\?>\s*/i, "").trim();
  if (!svg.startsWith("<svg")) throw new Error(`${name}: not an <svg> document`);
  if (/<script/i.test(svg)) throw new Error(`${name}: contains <script>`);
  if (/\son[a-z]+\s*=/i.test(svg)) throw new Error(`${name}: contains an event handler`);
  if (/(?:xlink:)?href\s*=\s*["'](?!#)/i.test(svg)) throw new Error(`${name}: contains an external href`);
  if (/<foreignObject/i.test(svg) || /url\(\s*["']?(?!#)/i.test(svg))
    throw new Error(`${name}: loads a resource`);
  return svg;
}

/** The two Archivo @font-face blocks of the UI's fonts.css with their `src` replaced by a base64 data URI. */
export function fontFaceCss(): string {
  const fonts = text("generated/fonts.css");
  const blocks = fonts.match(/@font-face\s*\{[^}]*\}/g) ?? [];
  const out: string[] = [];
  for (const file of FONT_FILES) {
    const block = blocks.find((b) => b.includes(`/${file}`));
    if (!block) throw new Error(`fonts.css has no @font-face for ${file}`);
    const uri = `url("data:font/woff2;base64,${read(`fonts/${file}`).toString("base64")}") format("woff2")`;
    out.push(block.replace(/src:\s*url\([^;]*;/, `src: ${uri};`));
  }
  // FX-5 (full audit A4 3): the Bengali and Devanagari fallbacks join the "Archivo" family for their own characters only (unicode-range), with
  // Archivo's descriptors so the browser treats them as one composite face: a name typed in those scripts prints, with no change to any font stack.
  // They have one weight; the 600 of a heading prints at 400.
  for (const f of PDF_FALLBACK_FONTS) {
    const uri = `url("data:font/woff2;base64,${read(`fonts/${pdfFallbackFileName(f)}`).toString("base64")}") format("woff2")`;
    out.push(
      `@font-face {\n  font-family: "Archivo";\n  font-style: normal;\n  font-weight: 400 600;\n  font-stretch: 100% 116%;\n  font-display: swap;\n  src: ${uri};\n  unicode-range: ${unicodeRange(f.ranges)};\n}`,
    );
  }
  return `${out.join("\n\n")}\n`;
}

export function buildAssetsSource(): string {
  const fontCss = fontFaceCss();
  const printCss = text("generated/print.css");
  const logos: Record<string, string> = {};
  for (const name of BRAND_LOGOS) logos[name] = cleanSvg(name, text(`brand/${name}`));
  const symbol = cleanSvg("logo-symbol-color.svg", text("brand/logo-symbol-color.svg"));
  const sha = createHash("sha256")
    .update(fontCss)
    .update("\0")
    .update(printCss)
    .update("\0")
    .update(JSON.stringify(logos))
    .update("\0")
    .update(symbol)
    .digest("hex");
  const j = (v: unknown) => JSON.stringify(v);
  return `// Generated by scripts/build-assets.ts (pnpm --filter @techaust/pdf build:assets). Do not edit; a drift test regenerates and compares.
// Browser Run only reads what is inlined, so the fonts are data URIs. TECHAUST_PDF_FONT_DATA is the marker of
// scripts/worker-budget.mjs: this file belongs in the jobs Worker only.
import type { BRAND_LOGOS } from "@techaust/core/settings";

export type BrandLogo = (typeof BRAND_LOGOS)[number];

/** @font-face rules with the Archivo woff2 files inlined (variable, weights 400 to 600, widths 100 to 116 %; the rupee sign U+20B9 in its own face), then the Noto Sans Bengali and Devanagari fallbacks under the same family for their scripts only (FX-5). */
export const TECHAUST_PDF_FONT_DATA: string = ${j(fontCss)};

/** packages/ui/generated/print.css (the @page size and margins, the colours, the print type scale). */
export const PDF_PRINT_CSS: string = ${j(printCss)};

/** The brand logos as inline SVG (checked: no script, no event handler, no external reference). */
export const PDF_LOGOS: Record<BrandLogo, string> = ${j(logos)};

/** The symbol (T and stem) in brand colours, for the page footer. */
export const PDF_SYMBOL: string = ${j(symbol)};

/** SHA-256 of the four values above, to see at a glance that a rebuild changed them. */
export const PDF_ASSETS_SHA256 = ${j(sha)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildAssetsSource());
  console.log(`wrote ${OUT}`);
}
