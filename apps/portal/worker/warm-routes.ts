// The portal's start-up dry run of its hot routes (M7.5 L39; B2's finding P1: every portal first run was over the 2.5 ms local line). The admin's pattern
// (apps/admin/worker/warm-routes.ts, CPU warm-up (b)1): the first request each route gets in a fresh isolate costs most (V8 compiles the route's code lazily,
// its inline caches start cold), inside the metered request. So while the module loads, the portal sends its hot routes (health, the link sign-in, `/me`,
// Home, the invoices list) through a SECOND instance of its own app (`createApp({}, { warm: true })`: the same middleware, guard, validators, handlers, row
// mappers and serialiser) on a made-up env:
//   - D1 is `warmDb` (@techaust/db/warm): an in-memory answer book of made-up rows (warm-fixtures/portal.ts, generated by
//     `node scripts/cpu-probe.mjs --write-fixtures` from the probe's sample set: "(sample)" names, @example.test addresses). Nothing is read from or written
//     to a database; a write is answered with its recorded rows changed and dropped.
//   - no other binding at all: no queue, R2 bucket, service or Rate Limiting binding (the limiter middleware lets a warm request through with no work), so
//     nothing can be sent or stored; the key pepper is a made-up value built from words, never a real one.
// Global scope refuses a Request with a body, a Response with a body, random values, timers and I/O, so a warm call is a bodiless Request whose JSON is handed
// to Hono's body cache, `c.json` answers without a body, and the link use takes a made-up session token and row ids (auth.ts `WARM_SESSION_TOKEN`): no call
// asks for a refused operation (each one costs workerd about 12 ms of start-up; a test counts them, warm-routes.test.ts). Nothing is stored, sent or
// logged, no request is counted and no `f: 1` first-run mark is set (index.ts). Never throws: each call is caught, and the result is the number of calls that
// answered below 400 (a test pins it under global-scope rules).
import {
  exposeToStartupProbe,
  type WarmCall,
  type WarmFixture,
  type WarmRows,
  warmDb,
} from "@techaust/db/warm";
import type { Hono } from "hono/tiny";
import type { ContentfulStatusCode } from "hono/utils/http-status";
import type { AppEnv, Ctx } from "./context.ts";

/** The portal's app type (index.ts `createApp`). */
type App = Hono<AppEnv, Record<string, never>, "/api">;

/**
 * The dry run's JSON bodies: workerd refuses a Request WITH a body at global scope, so a warm call is a bodiless Request whose JSON text is held here and
 * handed to Hono's body cache by the warm app's first middleware (`warmIn`). Only a warm app reads it; a real request is never in it.
 */
export const warmBodies = new WeakMap<Request, string>();

/** What a warm app's `c.json` does: the whole serialiser runs, the answer is a bodiless Response (allowed at global scope) with the same status. */
function warmJson(c: Ctx) {
  return (object: unknown, arg?: number | ResponseInit) => {
    JSON.stringify(object);
    const status = typeof arg === "number" ? arg : (arg?.status ?? 200);
    return c.body(null, status as ContentfulStatusCode);
  };
}

/** A warm app's first middleware (index.ts `createApp(..., { warm: true })`): the body from `warmBodies`, and `c.json` without a body. */
export async function warmIn(c: Ctx, next: () => Promise<void>): Promise<void> {
  const text = warmBodies.get(c.req.raw);
  // Hono keeps the PROMISE of each body reading in `bodyCache` (its type names the value); `c.req.json()` reads `text` from it.
  if (text !== undefined) Reflect.set(c.req.bodyCache, "text", Promise.resolve(text));
  // An own property over Hono's (an instance field), on this warm context only.
  Object.defineProperty(c, "json", { value: warmJson(c), configurable: true, writable: true });
  await next();
}

/**
 * The made-up env of the dry run: only what its hot routes read (M7.5 L39; the portal's bundle sits at its plan line, so nothing more): the answer book's D1,
 * `ENVIRONMENT` "warm" (health prints it; nothing of the real environments' rules applies) and the key pepper, base64 of 32 bytes as the real one (the HMAC
 * key import reads it so), built from words at run time (outside apps/portal/worker/warm-fixtures/, the path .gitleaks.toml allows, no secret-looking literal
 * is written). A hot route that came to need another binding would stop at it and answer 500 silently, which the pinned statuses show (warm-routes.test.ts).
 */
export function warmEnv(book: WarmRows, observe?: Parameters<typeof warmDb>[1]): Env {
  const env = {
    DB: warmDb(book, observe),
    ENVIRONMENT: "warm",
    PORTAL_KEY_PEPPER: btoa(["warm", "up", "portal", "pepper"].join("-").padEnd(32, "0")),
  };
  return env as unknown as Env;
}

/** The origin of every warm call (the CSRF check compares it with the request's own). */
const ORIGIN = "http://localhost:5174";
/** A made-up session cookie: the answer book holds the session row the guard reads for it. */
export const WARM_COOKIE = "__Host-ta_portal=warm-up-session-not-a-real-one";
const ctx: ExecutionContext = {
  // Work a warm call hands to `waitUntil` is not awaited, but its rejection is swallowed: never an unhandled rejection at start-up.
  waitUntil: (work: Promise<unknown>) => {
    Promise.resolve(work).catch(() => {});
  },
  passThroughOnException: () => {},
  props: {},
} as unknown as ExecutionContext;

/** Sends each call through the warm app on the env; the number that answered below 400. Never throws. `seen` (tests): each call's status, 0 when it threw. */
export async function warmRoutes(
  app: App,
  env: Env,
  calls: readonly WarmCall[],
  seen?: (call: WarmCall, status: number) => void,
): Promise<number> {
  let answered = 0;
  for (const call of calls) {
    let status = 0;
    try {
      const headers: Record<string, string> = { Origin: ORIGIN, Cookie: WARM_COOKIE };
      if (call.body !== undefined) headers["Content-Type"] = "application/json";
      const req = new Request(`${ORIGIN}/api/v1${call.path}`, { method: call.method, headers });
      if (call.body !== undefined) warmBodies.set(req, JSON.stringify(call.body));
      const res = await app.fetch(req, env, ctx);
      status = res.status;
      if (res.status < 400) answered++;
    } catch {
      // never stop a Worker from starting
    }
    seen?.(call, status);
  }
  return answered;
}

/**
 * The entry's whole start-up dry run, as index.ts calls it at top level: builds the warm app (`build` runs synchronously, so a throw there is caught too),
 * runs it once over the fixture's calls, turns any rejection into 0 and hands the work to the budget's start-up probe. Never throws, never rejects: whatever
 * goes wrong, the Worker starts and its real app is untouched.
 */
export function warmAtStartup(build: () => App, fixture: WarmFixture): Promise<number> {
  let work: Promise<number>;
  try {
    const app = build();
    work = warmRoutes(app, warmEnv(fixture.rows), fixture.calls);
  } catch {
    work = Promise.resolve(0);
  }
  const settled = work.catch(() => 0);
  exposeToStartupProbe(settled);
  return settled;
}
