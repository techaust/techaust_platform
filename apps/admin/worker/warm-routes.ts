// The start-up dry run of the hot routes (CPU warm-up task (b)1, 2026-11-02; docs/runs/cpu-warmup.md). The staging CPU reading showed that the first request
// each route gets in a fresh isolate costs most (V8 compiles the route's code lazily, its inline caches start cold), inside the metered request; running a
// path once beforehand removed about 85 % locally (M6.2 CPU diagnosis). So while the module loads, each Worker sends a few made-up requests through a SECOND
// instance of its own app (`createApp(..., { warm: true })`: the same middleware, guard, validators, handlers, models, views and serialiser) on a made-up env:
//   - D1 is `warmDb`: an in-memory answer book of made-up rows (warm-fixtures/*.ts, generated by `node scripts/cpu-probe.mjs --write-fixtures` from the probe's
//     sample set: "(sample)" names, @example.test addresses). Nothing is read from or written to a database; a write is answered "1 row changed" and dropped.
//   - queues, R2 buckets and service bindings accept and drop everything; the secrets are made-up test values (the admin tests' own), never a real one.
// Global scope refuses a Request with a body, a Response with a body, random values, timers and I/O, so a warm call is a bodiless Request whose JSON is handed
// to Hono's body cache, `c.json` answers without a body, and a step that needs a random value (a new id) ends that call there (silently). What ran up to that
// point is compiled and warm. Nothing is stored, sent or logged, no request is counted and no `f: 1` first-run mark is set (app.ts). Never throws: each call
// is caught, and the result is the number of calls that answered below 400 (a test pins it under global-scope rules, warm-routes.test.ts).
import { type App, warmBodies } from "./app.ts";

/** One made-up request: a path below `/api/v1`, its method and (for a write) its JSON body. */
export type WarmCall = { readonly method: string; readonly path: string; readonly body?: unknown };

/**
 * The answer book: FNV-1a of a statement's SQL → its made-up results (`p`: the parameters they were recorded for, kept only where one statement has several
 * entries; `r`: rows; `c`: rows changed).
 */
export type WarmRows = Readonly<
  Record<
    string,
    readonly { readonly p?: readonly unknown[]; readonly r: readonly unknown[]; readonly c: number }[]
  >
>;

/** A Worker's dry run: its calls and its answer book (warm-fixtures/<worker>.ts). */
export type WarmFixture = { readonly calls: readonly WarmCall[]; readonly rows: WarmRows };

/** FNV-1a (32 bits, hex) of a SQL text: the answer book's key. Also used by the fixture writer (scripts/cpu-probe.mjs), which must hash the same way. */
export function sqlKey(sql: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < sql.length; i++) {
    h ^= sql.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

/**
 * A fixture value as the Worker reads it: `{ $j: [...] }` (a made-up value under a secret-looking key, kept in pieces by the fixture writer so CI's secret scan
 * never sees a credential-shaped literal) is joined back; everything else is copied as it is.
 */
export function unpack(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(unpack);
  if (v !== null && typeof v === "object") {
    const pieces = (v as { $j?: unknown }).$j;
    if (Array.isArray(pieces) && Object.keys(v).length === 1) return pieces.join("");
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, unpack(x)]));
  }
  return v;
}

const sameParams = (a: readonly unknown[], b: readonly unknown[]) =>
  a.length === b.length && a.every((v, i) => v === b[i]);

/**
 * What the made-up D1 saw of one statement (tests only, early check 2): its SQL, whether it reads, whether the answer book held it (a read it does not hold
 * is a MISS: a stale fixture, answered with no rows), and how many rows it answered.
 */
export type WarmStatementSeen = {
  readonly sql: string;
  readonly read: boolean;
  readonly hit: boolean;
  readonly rows: number;
};

/**
 * A made-up D1 over the answer book: reads get the recorded rows (those recorded for the same parameters, else the first), writes report one row changed.
 * `observe` (tests): called once per statement answered, so a test can fail a stale fixture (a read missing from the book) instead of a quiet empty answer.
 */
export function warmDb(book: WarmRows, observe?: (seen: WarmStatementSeen) => void): D1Database {
  const answer = (sql: string, params: readonly unknown[]) => {
    const entries = book[sqlKey(sql)];
    const hit = entries?.find((e) => e.p !== undefined && sameParams(e.p, params)) ?? entries?.[0];
    const write = !/^\s*(SELECT|WITH)\b/i.test(sql);
    const rows = (hit?.r ?? []) as Record<string, unknown>[];
    observe?.({ sql, read: !write, hit: hit !== undefined, rows: rows.length });
    const changes = hit ? hit.c : write ? 1 : 0;
    return {
      success: true as const,
      results: rows.map((r) => unpack(r) as Record<string, unknown>),
      meta: {
        duration: 0,
        changes,
        last_row_id: 0,
        changed_db: changes > 0,
        rows_read: rows.length,
        rows_written: changes,
        size_after: 0,
      },
    };
  };
  const statement = (sql: string, params: readonly unknown[]): D1PreparedStatement => {
    const s = {
      sql,
      params,
      bind: (...values: unknown[]) => statement(sql, values),
      first: async (column?: string) => {
        const row = answer(sql, params).results[0] as Record<string, unknown> | undefined;
        if (row === undefined) return null;
        return column === undefined ? row : (row[column] ?? null);
      },
      all: async () => answer(sql, params),
      run: async () => answer(sql, params),
      raw: async (options?: { columnNames?: boolean }) => {
        const results = answer(sql, params).results;
        const rows = results.map((r) => (Array.isArray(r) ? r : Object.values(r)));
        if (!options?.columnNames) return rows;
        const first = results[0];
        return [first && !Array.isArray(first) ? Object.keys(first) : [], ...rows];
      },
    };
    return s as unknown as D1PreparedStatement;
  };
  const db = {
    prepare: (sql: string) => statement(sql, []),
    batch: async (statements: D1PreparedStatement[]) =>
      statements.map((st) => {
        const s = st as unknown as { sql: string; params: readonly unknown[] };
        return answer(s.sql, s.params);
      }),
    exec: async () => ({ count: 0, duration: 0 }),
    withSession: () => db,
    dump: async () => new ArrayBuffer(0),
  };
  return db as unknown as D1Database;
}

const drop = { send: async () => {}, sendBatch: async () => {} };
const noObject = {
  get: async () => null,
  head: async () => null,
  put: async () => null,
  delete: async () => {},
  list: async () => ({ objects: [], truncated: false, delimitedPrefixes: [] }),
};
/** A service binding that answers at once without a body (global scope allows that Response). */
const answers = { fetch: async () => new Response(null, { status: 200 }) };

/**
 * The made-up env of a dry run: the answer book's D1, bindings that drop everything, the local vars and the finance Worker's made-up test key pair; `extra`
 * adds a Worker's own made-up values (the front's sign-in keys, warm-front.ts: the API and finance bundles must never name them). `ENVIRONMENT` is "warm" so
 * nothing of the real environments' rules applies. The gateway transport is "unset" (gateway/config.ts `transportOf` allows "stub" only when ENVIRONMENT is
 * "local"), so any gateway path in a dry run answers 503 `gateway_unavailable` and no Razorpay call can be made from here; no hot route of the dry run
 * reaches one. `observe` (tests): see warmDb.
 */
export function warmEnv(
  book: WarmRows,
  extra: Readonly<Record<string, string>> = {},
  observe?: (seen: WarmStatementSeen) => void,
): Env {
  const env = {
    DB: warmDb(book, observe),
    EMAIL_QUEUE: drop,
    PDF_QUEUE: drop,
    LEADS_QUEUE: drop,
    FILES: noObject,
    DOCS: noObject,
    ADMIN_API: answers,
    ADMIN_FINANCE: answers,
    ENVIRONMENT: "warm",
    PAYMENTS_LIVE_ALLOWED: "false",
    LEAD_PURGE_MODE: "dry_run",
    TURNSTILE_SITE_KEY: "1x00000000000000000000AA",
    TURNSTILE_HOSTNAMES: "localhost",
    PORTAL_ORIGIN: "http://localhost:5174",
    PORTAL_URL: "http://localhost:5174/",
    GATEWAY_TRANSPORT: "stub",
    // Made-up test values built from words (no secret-looking literal in the source: CI's secret scan reads every commit).
    RAZORPAY_KEY_ID: ["rzp", "test", "WARMUP"].join("_"),
    RAZORPAY_KEY_SECRET: ["warm", "up", "razorpay"].join("-"),
    ...extra,
  };
  return env as unknown as Env;
}

/** The origin of every warm call (the CSRF check compares it with the request's own). */
const ORIGIN = "http://localhost:5173";
/** A made-up session cookie: the answer book holds the session row the guard reads for it. */
export const WARM_COOKIE = "__Host-ta_admin=warm-up-session-not-a-real-one";
const ctx: ExecutionContext = {
  // Work a warm call hands to `waitUntil` is not awaited, but its rejection is swallowed (early check finding 4): never an unhandled rejection at start-up.
  waitUntil: (work: Promise<unknown>) => {
    Promise.resolve(work).catch(() => {});
  },
  passThroughOnException: () => {},
  props: {},
} as unknown as ExecutionContext;

/** Sends each call through the warm app on the env; the number that answered below 400. Never throws. `seen` (tests): each call's status, 0 when it threw. */
export async function warmRoutes(
  app: App,
  env: Env,
  calls: readonly WarmCall[],
  seen?: (call: WarmCall, status: number) => void,
): Promise<number> {
  let answered = 0;
  for (const call of calls) {
    let status = 0;
    try {
      const headers: Record<string, string> = { Origin: ORIGIN, Cookie: WARM_COOKIE };
      if (call.body !== undefined) headers["Content-Type"] = "application/json";
      const req = new Request(`${ORIGIN}/api/v1${call.path}`, { method: call.method, headers });
      if (call.body !== undefined) warmBodies.set(req, JSON.stringify(unpack(call.body)));
      const res = await app.fetch(req, env, ctx);
      status = res.status;
      if (res.status < 400) answered++;
    } catch {
      // never stop a Worker from starting
    }
    seen?.(call, status);
  }
  return answered;
}

/**
 * The start-up probe's collector (scripts/worker-budget.mjs `STARTUP_PROBE`, CPU warm-up fix round, early check 1a): the probe puts a function by this name
 * in its sandbox's global scope and waits for what it is handed, so the budget times the dry run's microtasks as well as the module's evaluation. Workerd
 * has no such global, so in a deployed Worker this reads one missing property and does nothing.
 */
const STARTUP_PROBE = "__techaustStartupProbe";
/** Hands an entry's start-up work to the budget's start-up probe, when one is listening; never throws. */
export function exposeToStartupProbe(work: Promise<unknown>): void {
  try {
    const collect = (globalThis as Record<string, unknown>)[STARTUP_PROBE];
    if (typeof collect === "function") collect(work);
  } catch {
    // never stop a Worker from starting
  }
}

/** How many passes an entry's start-up makes over its calls: V8 compiles on the first, and the next ones warm the inline caches further. */
export const WARM_ROUNDS = 1;

/** An entry's start-up dry run: `rounds` passes over the fixture's calls on its made-up env (`extra`: see warmEnv); the count of the last pass. Never throws. */
export async function warmStart(
  app: App,
  fixture: WarmFixture,
  extra: Readonly<Record<string, string>> = {},
  rounds = WARM_ROUNDS,
): Promise<number> {
  const env = warmEnv(fixture.rows, extra);
  let answered = 0;
  for (let i = 0; i < rounds; i++) answered = await warmRoutes(app, env, fixture.calls);
  return answered;
}

/**
 * An entry's whole start-up dry run, as each entry calls it at top level (early check finding 4): builds the warm app (`build` runs synchronously, so a throw
 * there is caught too), runs it (`warmStart`), turns any rejection into 0 and hands the work to the budget's start-up probe. Never throws, never rejects:
 * whatever goes wrong, the Worker starts and its real app is untouched.
 */
export function warmAtStartup(
  build: () => App,
  fixture: WarmFixture,
  extra: Readonly<Record<string, string>> = {},
): Promise<number> {
  let work: Promise<number>;
  try {
    work = warmStart(build(), fixture, extra);
  } catch {
    work = Promise.resolve(0);
  }
  const settled = work.catch(() => 0);
  exposeToStartupProbe(settled);
  return settled;
}
