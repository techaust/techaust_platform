const drop = { send: async () => {}, sendBatch: async () => {} };
const noObject = {
  get: async () => null,
  head: async () => null,
  put: async () => null,
  delete: async () => {},
  list: async () => ({ objects: [], truncated: false, delimitedPrefixes: [] }),
};
/** A service binding that answers at once without a body (global scope allows that Response). */
const answers = { fetch: async () => new Response(null, { status: 200 }) };
/**
 * The finance Worker's `ADMIN_ADVANCE` in its dry run (the fourth admin Worker, brief D.7): the Owner's "Try again" route runs against this stub, which answers
 * a made-up `issued` at once and never calls the invoices Worker (that Worker dry-runs the advance itself, warm-advance.ts).
 */
const advanceAnswers = { issueGatewayAdvance: async () => ({ result: "issued" as const, number: "WARM/1" }) };

/** Made-up ids in UUIDv7 form from a counter (`00000000-0000-7000-8000-000000000001`, …): global scope refuses random values (warm-rpc.ts, warm-advance.ts). */
export function warmIds(): () => string {
  let n = 0;
  return () => `00000000-0000-7000-8000-${(++n).toString(16).padStart(12, "0")}`;
}

/**
 * The made-up env of a dry run: the answer book's D1, bindings that drop everything, the local vars and the finance Worker's made-up test key pair; `extra`
 * adds a Worker's own made-up values (the front's sign-in keys, warm-front.ts: the API and finance bundles must never name them). `ENVIRONMENT` is "warm" so
 * nothing of the real environments' rules applies. GATEWAY_TRANSPORT is not set, so the gateway transport is "unset" (gateway/config.ts `transportOf`; it would
 * allow "stub" only when ENVIRONMENT is "local" anyway), so any gateway path in a dry run answers 503 `gateway_unavailable` and no Razorpay call can be made from here; no hot route of the dry run
 * reaches one. `observe` (tests): see warmDb.
 */
export function warmEnv(
  book: WarmRows,
  extra: Readonly<Record<string, string>> = {},
  observe?: (seen: WarmStatementSeen) => void,
): Env {
  const env = {
    DB: warmDb(book, observe),
    EMAIL_QUEUE: drop,
    PDF_QUEUE: drop,
    LEADS_QUEUE: drop,
    FILES: noObject,
    DOCS: noObject,
    ADMIN_API: answers,
    ADMIN_FINANCE: answers,
    // The fourth admin Worker (2026-11-03): the front's binding to the invoices Worker (its forwarded hot routes: an invoice, the issue, the dashboard), and
    // finance's to the invoices Worker's `GatewayAdvance` (the review retry route).
    ADMIN_INVOICES: answers,
    ADMIN_ADVANCE: advanceAnswers,
    ENVIRONMENT: "warm",
    PAYMENTS_LIVE_ALLOWED: "false",
    TURNSTILE_SITE_KEY: "1x00000000000000000000AA",
    TURNSTILE_HOSTNAMES: "localhost",
    PORTAL_ORIGIN: "http://localhost:5174",
    PORTAL_URL: "http://localhost:5174/",
    // GATEWAY_TRANSPORT is left out on purpose: unset, `transportOf` answers "unset" whatever ENVIRONMENT says (review finding 4).
    // Made-up test values built from words at run time: outside apps/admin/worker/warm-fixtures/ (the one path .gitleaks.toml allows) no secret-looking
    // literal is ever written, since CI's secret scan reads every commit.
    RAZORPAY_KEY_ID: ["rzp", "test", "WARMUP"].join("_"),
    RAZORPAY_KEY_SECRET: ["warm", "up", "razorpay"].join("-"),
    ...extra,
  };
  return env as unknown as Env;
}

/** The origin of every warm call (the CSRF check compares it with the request's own). */
const ORIGIN = "http://localhost:5173";
/** A made-up session cookie: the answer book holds the session row the guard reads for it. */
export const WARM_COOKIE = "__Host-ta_admin=warm-up-session-not-a-real-one";
const ctx: ExecutionContext = {
  // Work a warm call hands to `waitUntil` is not awaited, but its rejection is swallowed (early check finding 4): never an unhandled rejection at start-up.
  waitUntil: (work: Promise<unknown>) => {
    Promise.resolve(work).catch(() => {});
  },
  passThroughOnException: () => {},
  props: {},
} as unknown as ExecutionContext;

/** Sends each call through the warm app on the env; the number that answered below 400. Never throws. `seen` (tests): each call's status, 0 when it threw. */
export async function warmRoutes(
  app: App,
  env: Env,
  calls: readonly WarmCall[],
  seen?: (call: WarmCall, status: number) => void,
): Promise<number> {
  let answered = 0;
  for (const call of calls) {
    let status = 0;
    try {
      const headers: Record<string, string> = { Origin: ORIGIN, Cookie: WARM_COOKIE };
      if (call.body !== undefined) headers["Content-Type"] = "application/json";
      const req = new Request(`${ORIGIN}/api/v1${call.path}`, { method: call.method, headers });
      if (call.body !== undefined) warmBodies.set(req, JSON.stringify(call.body));
      const res = await app.fetch(req, env, ctx);
      status = res.status;
      if (res.status < 400) answered++;
    } catch {
      // never stop a Worker from starting
    }
    seen?.(call, status);
  }
  return answered;
}

/** How many passes an entry's start-up makes over its calls: V8 compiles on the first, and the next ones warm the inline caches further. */
export const WARM_ROUNDS = 1;

/** An entry's start-up dry run: `rounds` passes over the fixture's calls on its made-up env (`extra`: see warmEnv); the count of the last pass. Never throws. */
export async function warmStart(
  app: App,
  fixture: WarmFixture,
  extra: Readonly<Record<string, string>> = {},
  rounds = WARM_ROUNDS,
): Promise<number> {
  const env = warmEnv(fixture.rows, extra);
  let answered = 0;
  for (let i = 0; i < rounds; i++) answered = await warmRoutes(app, env, fixture.calls);
  return answered;
}

/**
 * An entry's whole start-up dry run, as each entry calls it at top level (early check finding 4): builds the warm app (`build` runs synchronously, so a throw
 * there is caught too), runs it (`warmStart`), turns any rejection into 0 and hands the work to the budget's start-up probe. Never throws, never rejects:
 * whatever goes wrong, the Worker starts and its real app is untouched.
 */
export function warmAtStartup(
  build: () => App,
  fixture: WarmFixture,
  extra: Readonly<Record<string, string>> = {},
): Promise<number> {
  let work: Promise<number>;
  try {
    work = warmStart(build(), fixture, extra);
  } catch {
    work = Promise.resolve(0);
  }
  const settled = work.catch(() => 0);
  exposeToStartupProbe(settled);
  return settled;
}
