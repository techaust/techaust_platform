// The admin finance Worker's start-up dry run of its gateway RPC entrypoints (M6.4 L31, early check 2 finding 4; the HTTP routes' own is warm-routes.ts). The
// local probe read the PayPal capture RPC's first call at 9.8 ms (Razorpay's processEvent 4.7): V8 compiles the capture, judge, fee, payment and ledger code
// lazily, inside the first metered call. So while the module loads, the same functions the entrypoints call (`capturePayPalReturn`, `processEvent`,
// `refreshCheckoutById`, `createLinkFor`) run once on a made-up env:
//   - D1 is `warmDb` over the answer book warm-fixtures/finance-rpc.ts (generated by `node scripts/cpu-probe.mjs --write-fixtures` from the probe's made-up
//     sample set, as the HTTP fixtures are); a write is answered "1 row changed" and dropped;
//   - PayPal is the local simulator's answers (`payPalStubAnswer`) through a transport that makes no Response and sets no timer (`WARM_PAYPAL_TRANSPORT`, keyed by
//     a symbol no real env can carry), with made-up client keys; the token it mints is dropped at the end, and its cache key could never match real keys anyway;
//   - every new id comes from a counter (global scope refuses random values), and the clock is workerd's start-up clock.
// The capture is dry-run twice: a payer in the US (the confirmed batch) and in India (RA-38's `not_export_receipt`, the pending batch), so both judges' paths and
// both payment batches compile. Nothing is stored, sent or logged; never throws.
import type { CreateLinkArgs } from "@techaust/core/gateway-rpc";
import { WARM_PAYPAL_TRANSPORT } from "./gateway/config.ts";
import { processEvent } from "./gateway/events.ts";
import { createLinkFor, refreshCheckoutById } from "./gateway/links.ts";
import { payPalStubAnswer } from "./gateway/paypal.ts";
import { capturePayPalReturn } from "./gateway/paypal-capture.ts";
import { dropPayPalToken } from "./gateway/paypal-token.ts";
import { exposeToStartupProbe, type WarmRows, type WarmStatementSeen, warmEnv } from "./warm-routes.ts";

/** One made-up RPC call (its entrypoint method and arguments, from the probe's sample set); `country`: the payer PayPal reports (default the simulator's US). */
export type WarmRpcCall =
  | {
      readonly m: "capturePayPalReturn";
      readonly args: { readonly checkoutId: string; readonly token: string | null };
      readonly country?: string;
    }
  | { readonly m: "processEvent"; readonly args: { readonly eventId: string } }
  | { readonly m: "refreshCheckout"; readonly args: { readonly checkoutId: string } }
  | { readonly m: "createLink"; readonly args: CreateLinkArgs };

/** The RPC dry run: its calls and its answer book (warm-fixtures/finance-rpc.ts). */
export type WarmRpcFixture = { readonly calls: readonly WarmRpcCall[]; readonly rows: WarmRows };

/** Made-up ids in UUIDv7 form from a counter (`00000000-0000-7000-8000-000000000001`, …). */
export function warmIds(): () => string {
  let n = 0;
  return () => `00000000-0000-7000-8000-${(++n).toString(16).padStart(12, "0")}`;
}

/** The simulator's body with the payer and the PayPal account in `country` (an order answer carries both; a capture answer neither). */
function withCountry(body: unknown, country: string): unknown {
  if (typeof body !== "object" || body === null) return body;
  const o = body as Record<string, unknown>;
  if (o.payer) o.payer = { address: { country_code: country } };
  if (o.payment_source) o.payment_source = { paypal: { address: { country_code: country } } };
  return o;
}

/**
 * The dry run's PayPal transport: the simulator's answer as a Response-shaped object with no body stream (global scope refuses a Response with a body); the
 * client reads only `status`, `json()` and `body?.cancel()`.
 */
export function warmPayPalFetch(country?: string): typeof fetch {
  const f = async (input: RequestInfo | URL, init?: RequestInit) => {
    const a = payPalStubAnswer(input, init);
    const body = country ? withCountry(a.body, country) : a.body;
    return { status: a.status, body: null, json: async () => body };
  };
  return f as unknown as typeof fetch;
}

/** What one call answered, in a word (tests pin these): the return's state, the event's or refresh's result, `link` or the link's refusal; `threw` when it threw. */
const wordOf = (r: unknown): string => {
  if (typeof r !== "object" || r === null) return "none";
  const o = r as Record<string, unknown>;
  if (typeof o.state === "string") return o.state;
  if (typeof o.result === "string") return o.result;
  if (o.ok === true) return "link";
  return typeof o.error === "string" ? o.error : "none";
};

/**
 * Runs each call once on the made-up env; the words of what they answered. Never throws. `observe` (tests): every statement the made-up D1 answered.
 * `now`: workerd's start-up clock unless a test gives another.
 */
export async function warmRpc(
  fixture: WarmRpcFixture,
  observe?: (call: WarmRpcCall, seen: WarmStatementSeen) => void,
  now = Date.now(),
): Promise<string[]> {
  const words: string[] = [];
  try {
    for (const call of fixture.calls) {
      let word = "threw";
      try {
        const env = Object.assign(
          warmEnv(fixture.rows, {}, (s) => observe?.(call, s)),
          {
            // Made-up client keys, built from words at run time (CI's secret scan reads every commit); the sandbox origin only (Settings' mode is the book's).
            PAYPAL_CLIENT_ID: ["warm", "up", "paypal", "client"].join("-"),
            PAYPAL_CLIENT_SECRET: ["warm", "up", "paypal", "keys"].join("-"),
          },
          { [WARM_PAYPAL_TRANSPORT]: warmPayPalFetch("country" in call ? call.country : undefined) },
        ) as Env;
        const ids = warmIds();
        switch (call.m) {
          case "capturePayPalReturn":
            word = wordOf(await capturePayPalReturn(env, call.args, now, ids));
            break;
          case "processEvent":
            word = wordOf(await processEvent(env, call.args.eventId, now, ids));
            break;
          case "refreshCheckout":
            word = wordOf(await refreshCheckoutById(env, call.args.checkoutId, now, ids));
            break;
          case "createLink":
            word = wordOf(await createLinkFor(env, call.args, now, ids));
            break;
        }
      } catch {
        // never stop a Worker from starting
      }
      words.push(`${call.m} ${word}`);
    }
  } catch {
    // a broken fixture: nothing more is run
  } finally {
    // The made-up token is never kept (its cache key could not match real keys, but nothing of the dry run should outlive it).
    dropPayPalToken();
  }
  return words;
}

/** The entry's top-level call: the dry run, handed to the budget's start-up probe; the number of calls that answered as a real call would. Never rejects. */
export function warmRpcAtStartup(fixture: WarmRpcFixture): Promise<number> {
  const work = warmRpc(fixture)
    .then(
      (w) =>
        w.filter((x) => !/ (threw|none|retry|no_open_link|not_found|gateway_unavailable)$/.test(x)).length,
    )
    .catch(() => 0);
  exposeToStartupProbe(work);
  return work;
}
