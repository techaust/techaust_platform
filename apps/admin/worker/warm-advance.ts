// The admin invoices Worker's start-up dry run of its `GatewayAdvance` entrypoint (the fourth admin Worker, 2026-11-03, ADM-G-02, ADM-PAY-01; brief D.7, early
// check finding 7; the M6.4 L31 pattern of warm-rpc.ts, which this Worker may not import: it holds gateway client code). The automatic tax invoice of a proforma
// paid online is a money path whose first call compiles the invoice read, the tax engine, the seal and the issue batch lazily, inside the metered RPC. So while
// the module loads, `issueGatewayAdvance` (the function the entrypoint calls) runs once on a made-up env:
//   - D1 is `warmDb` over the answer book warm-fixtures/invoices-rpc.ts (generated by `node scripts/cpu-probe.mjs --write-fixtures` from the probe's made-up
//     sample set: "(sample)" names, @example.test addresses); a write is answered by the rows it changed when recorded, and dropped;
//   - every new id comes from a counter (global scope refuses random values: warm-routes.ts `warmIds`), and the clock is workerd's start-up clock;
//   - the PDF queue drops the message; no gateway is called (the advance makes no gateway call at all).
// Nothing is stored, sent or logged (the entrypoint's `ev:"rpc"` line is written by the class, which the dry run does not use); never throws.
import { issueGatewayAdvance } from "./gateway/advance.ts";
import {
  exposeToStartupProbe,
  type WarmRows,
  type WarmStatementSeen,
  warmEnv,
  warmIds,
} from "./warm-routes.ts";

/** One made-up `GatewayAdvance` call (its method and arguments, from the probe's sample set). */
export type WarmAdvanceCall = {
  readonly m: "issueGatewayAdvance";
  readonly args: { readonly paymentId: string };
};

/** The advance dry run: its calls and its answer book (warm-fixtures/invoices-rpc.ts). */
export type WarmAdvanceFixture = { readonly calls: readonly WarmAdvanceCall[]; readonly rows: WarmRows };

/** Runs each call once on the made-up env; `<method> <result>` per call (`threw` when it threw). Never throws. `observe` (tests): every statement answered. */
export async function warmAdvance(
  fixture: WarmAdvanceFixture,
  observe?: (call: WarmAdvanceCall, seen: WarmStatementSeen) => void,
): Promise<string[]> {
  const words: string[] = [];
  try {
    for (const call of fixture.calls) {
      let word = "threw";
      try {
        const env = warmEnv(fixture.rows, {}, (s) => observe?.(call, s));
        word = (await issueGatewayAdvance(env, call.args.paymentId, { ids: warmIds() })).result;
      } catch {
        // never stop a Worker from starting
      }
      words.push(`${call.m} ${word}`);
    }
  } catch {
    // a broken fixture: nothing more is run
  }
  return words;
}

/** The entry's top-level call: the dry run, handed to the budget's start-up probe; the number of calls that issued. Never rejects. */
export function warmAdvanceAtStartup(fixture: WarmAdvanceFixture): Promise<number> {
  const work = warmAdvance(fixture)
    .then((w) => w.filter((x) => x.endsWith(" issued")).length)
    .catch(() => 0);
  exposeToStartupProbe(work);
  return work;
}
